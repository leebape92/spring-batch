-- 테스트용(H2) 테이블. 운영 MySQL 스크립트(db/mysql/schema.sql)와 같은 구조.
CREATE TABLE IF NOT EXISTS TB_ORDER (
    order_id      BIGINT       NOT NULL PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    status_code   VARCHAR(20)  NOT NULL,
    amount        BIGINT       DEFAULT 0 NOT NULL,
    ordered_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at    TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TB_ORDER_STATUS_HIST (
    hist_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT       NOT NULL,
    before_status VARCHAR(20)  NOT NULL,
    after_status  VARCHAR(20)  NOT NULL,
    changed_by    VARCHAR(50)  DEFAULT 'BATCH' NOT NULL,
    changed_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
);
